import { modPow } from './CryptoUtils.js';

/**
 * Man-in-the-Middle (MITM) Diffie–Hellman Attack Simulation Model
 * 
 * Demonstrates the fundamental vulnerability of unauthenticated Diffie-Hellman:
 * Mallory intercepts public keys in transit, injects her own fake public values,
 * and negotiates two independent shared keys.
 */
export class MITMSimulation {
  /**
   * @param {number|bigint} p Prime modulus
   * @param {number|bigint} g Generator base
   * @param {number|bigint} a Alice's private exponent
   * @param {number|bigint} b Bob's private exponent
   * @param {number|bigint} mA Mallory's private exponent for Alice tunnel
   * @param {number|bigint} mB Mallory's private exponent for Bob tunnel
   */
  constructor(p, g, a, b, mA, mB) {
    this.p = BigInt(p);
    this.g = BigInt(g);
    this.a = BigInt(a);
    this.b = BigInt(b);
    this.mA = BigInt(mA);
    this.mB = BigInt(mB);

    // 1. Legitimate Public Keys generated by endpoints
    this.A = modPow(this.g, this.a, this.p);
    this.B = modPow(this.g, this.b, this.p);

    // 2. Mallory's forged public keys substituted on the wire
    this.MA = modPow(this.g, this.mA, this.p); // Sent to Alice (spoofing Bob)
    this.MB = modPow(this.g, this.mB, this.p); // Sent to Bob (spoofing Alice)

    // 3. Alice computes shared key using incoming MA
    this.KaAlice = modPow(this.MA, this.a, this.p);

    // 4. Mallory computes corresponding shared key with Alice using A
    this.KaMallory = modPow(this.A, this.mA, this.p);

    // 5. Bob computes shared key using incoming MB
    this.KbBob = modPow(this.MB, this.b, this.p);

    // 6. Mallory computes corresponding shared key with Bob using B
    this.KbMallory = modPow(this.B, this.mB, this.p);

    // 7. Security condition checks
    this.aliceMalloryMatch = (this.KaAlice === this.KaMallory);
    this.bobMalloryMatch = (this.KbBob === this.KbMallory);
    this.secretsAreSplit = (this.KaAlice !== this.KbBob);
  }

  /**
   * Educational simulation of message tampering
   */
  simulateTamperedMessage(originalPlaintext = 'Transfer $1,000 from Alice to Bob') {
    const tamperedPlaintext = originalPlaintext.replace(/\$1,?000/g, '$50,000 to Mallory');

    return {
      aliceOriginal: originalPlaintext,
      aliceKey: this.KaAlice.toString(),
      encryptedByAlice: `[Ciphertext encrypted with K_Alice = ${this.KaAlice}]`,
      malloryDecrypted: originalPlaintext,
      malloryTampered: tamperedPlaintext,
      malloryKeyBob: this.KbMallory.toString(),
      reEncryptedByMallory: `[Ciphertext re-encrypted with K_Bob = ${this.KbBob}]`,
      bobReceived: tamperedPlaintext,
      compromiseStatus: 'ATTACK SUCCEEDED: Mallory intercepted, read, modified, and re-encrypted the ciphertext undetected by either endpoint.'
    };
  }

  /**
   * Clean mathematical representations for academic display (no raw LaTeX escape strings)
   */
  getMathDetails() {
    return {
      tunnelAlice: {
        title: 'Tunnel 1: Alice ⇄ Mallory',
        aliceReceives: `Alice receives substituted key M_A = ${this.MA} (believing it is Bob's B)`,
        aliceCalc: `K_Alice = (M_A)ᵃ mod p = ${this.MA}^${this.a} mod ${this.p} = ${this.KaAlice}`,
        malloryCalc: `K_Mallory-Alice = A^(m_A) mod p = ${this.A}^${this.mA} mod ${this.p} = ${this.KaMallory}`,
        sharedKey: this.KaAlice.toString(),
        matched: this.aliceMalloryMatch
      },
      tunnelBob: {
        title: 'Tunnel 2: Mallory ⇄ Bob',
        bobReceives: `Bob receives substituted key M_B = ${this.MB} (believing it is Alice's A)`,
        bobCalc: `K_Bob = (M_B)ᵇ mod p = ${this.MB}^${this.b} mod ${this.p} = ${this.KbBob}`,
        malloryCalc: `K_Mallory-Bob = B^(m_B) mod p = ${this.B}^${this.mB} mod ${this.p} = ${this.KbMallory}`,
        sharedKey: this.KbBob.toString(),
        matched: this.bobMalloryMatch
      },
      vivaTakeaway: {
        splitStatus: this.secretsAreSplit 
          ? `Keys are SPLIT: K_Alice = ${this.KaAlice} ≠ K_Bob = ${this.KbBob}`
          : `Mallory knows both sides' keys: ${this.KaAlice}`,
        explanation: 'Because unauthenticated Diffie-Hellman lacks cryptographic identity binding, endpoints have no way to verify who truly created public keys A and B.'
      }
    };
  }
}
